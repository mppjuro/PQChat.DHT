#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
JUnit Test Results Markdown & Console Summarizer for Android Instrumented Tests.

Discovers XML test reports generated by Android instrumented tests (connectedDebugAndroidTest),
prints exact failed test classes, method names, failure messages, and full stacktraces directly
to the console stdout, and appends a structured Markdown summary to $GITHUB_STEP_SUMMARY.
"""

import glob
import os
import sys
import xml.etree.ElementTree as ET

if hasattr(sys.stdout, 'reconfigure'):
    try:
        sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    except Exception:
        pass
if hasattr(sys.stderr, 'reconfigure'):
    try:
        sys.stderr.reconfigure(encoding='utf-8', errors='replace')
    except Exception:
        pass

def find_test_xml_files():
    search_patterns = [
        os.path.join("app", "build", "outputs", "androidTest-results", "**", "*.xml"),
        os.path.join("app", "build", "reports", "androidTests", "**", "*.xml"),
    ]
    xml_files = []
    for pattern in search_patterns:
        for f in glob.glob(pattern, recursive=True):
            if os.path.isfile(f) and f.endswith(".xml") and f not in xml_files:
                xml_files.append(f)
    return xml_files

def parse_junit_xml(file_path):
    results = []
    try:
        tree = ET.parse(file_path)
        root = tree.getroot()
        testcases = root.findall(".//testcase")
        for tc in testcases:
            classname = tc.attrib.get("classname", "UnknownClass")
            name = tc.attrib.get("name", "UnknownTest")
            time = tc.attrib.get("time", "0.0")

            failure = tc.find("failure")
            error = tc.find("error")
            skipped = tc.find("skipped")

            status = "PASSED"
            message = ""
            details = ""

            if failure is not None:
                status = "FAILED"
                message = failure.attrib.get("message", failure.attrib.get("type", "Test Failed"))
                details = (failure.text or "").strip()
            elif error is not None:
                status = "ERROR"
                message = error.attrib.get("message", error.attrib.get("type", "Execution Error"))
                details = (error.text or "").strip()
            elif skipped is not None:
                status = "SKIPPED"
                message = skipped.attrib.get("message", "Skipped")

            results.append({
                "class": classname.split(".")[-1],
                "full_class": classname,
                "name": name,
                "time": time,
                "status": status,
                "message": message,
                "details": details,
            })
    except Exception as e:
        sys.stderr.write(f"Warning: Failed to parse {file_path}: {e}\n")
    return results

def write_step_summary(markdown_text):
    summary_path = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary_path:
        try:
            with open(summary_path, "a", encoding="utf-8") as f:
                f.write(markdown_text + "\n")
        except Exception as e:
            sys.stderr.write(f"Warning: Failed to write to GITHUB_STEP_SUMMARY: {e}\n")

def main():
    xml_files = find_test_xml_files()
    if not xml_files:
        msg = "No JUnit XML test result files discovered under app/build/."
        print(f"[INFO] {msg}")
        write_step_summary(f"ℹ️ {msg}")
        return

    all_tests = {}
    for f in xml_files:
        for item in parse_junit_xml(f):
            key = f"{item['full_class']}#{item['name']}"
            all_tests[key] = item

    if not all_tests:
        msg = "Found XML test result files but no <testcase> entries were recorded."
        print(f"[INFO] {msg}")
        write_step_summary(f"ℹ️ {msg}")
        return

    total = len(all_tests)
    failed = [t for t in all_tests.values() if t["status"] in ("FAILED", "ERROR")]
    skipped = [t for t in all_tests.values() if t["status"] == "SKIPPED"]
    passed = [t for t in all_tests.values() if t["status"] == "PASSED"]

    # 1. Print directly to console log (stdout)
    print("=" * 80)
    print(f"INSTRUMENTED TEST RESULTS (AVD API 34):")
    print(f"  Total: {total} | Passed: {len(passed)} | Failed: {len(failed)} | Skipped: {len(skipped)}")
    print("=" * 80)

    if failed:
        print("\n[FAILED] The following test cases failed:")
        for idx, f in enumerate(failed, 1):
            print("-" * 80)
            print(f"[{idx}] {f['full_class']}#{f['name']} -> {f['status']}")
            print(f"Message: {f['message']}")
            print("Stacktrace:")
            print(f["details"] or "No stacktrace recorded.")
        print("-" * 80 + "\n")
    else:
        print("\n[SUCCESS] All instrumented tests passed successfully!\n")

    # 2. Build Markdown for GITHUB_STEP_SUMMARY
    md_lines = [
        "### 📱 Instrumented AndroidTest (AVD) Execution Summary",
        "",
        f"- **Total Tests Executed:** `{total}`",
        f"- **Passed:** `{len(passed)}` ✅",
        f"- **Failed:** `{len(failed)}` ❌",
        f"- **Skipped:** `{len(skipped)}` ⏭️",
        ""
    ]

    if failed:
        md_lines.append("#### ❌ Failed Test Cases")
        md_lines.append("")
        md_lines.append("| Class | Test Method | Status | Summary |")
        md_lines.append("| :--- | :--- | :---: | :--- |")
        for f in failed:
            clean_msg = f['message'].replace("\n", " ").replace("|", "\\|")[:120]
            md_lines.append(f"| `{f['class']}` | `{f['name']}` | **{f['status']}** | {clean_msg} |")
        md_lines.append("")

        md_lines.append("#### 🔍 Failure Trace Details")
        md_lines.append("")
        for f in failed:
            md_lines.append("<details>")
            md_lines.append(f"<summary><b>{f['class']}.{f['name']}</b>: <i>{f['message'][:100]}</i></summary>")
            md_lines.append("")
            md_lines.append("```text")
            detail_lines = f["details"].splitlines()[:50]
            md_lines.append("\n".join(detail_lines) or "No stack trace recorded.")
            md_lines.append("```")
            md_lines.append("</details>")
            md_lines.append("")
    else:
        md_lines.append("🎉 **All instrumented tests passed successfully!**")
        md_lines.append("")

    write_step_summary("\n".join(md_lines))

if __name__ == "__main__":
    main()
