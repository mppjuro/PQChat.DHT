#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
JUnit Test Results Markdown Summarizer for GitHub Actions Job Summary.

Discovers XML test reports generated by Android instrumented tests (connectedDebugAndroidTest)
and formats a structured Markdown summary including test counts, pass/fail status, and detailed
failure trace snippets.
"""

import glob
import os
import sys
import xml.etree.ElementTree as ET

def find_test_xml_files():
    search_patterns = [
        os.path.join("app", "build", "outputs", "androidTest-results", "**", "*.xml"),
        os.path.join("app", "build", "reports", "androidTests", "**", "*.xml"),
    ]
    xml_files = []
    for pattern in search_patterns:
        for f in glob.glob(pattern, recursive=True):
            if os.path.isfile(f) and f.endswith(".xml") and f not in xml_files:
                xml_files.append(f)
    return xml_files

def parse_junit_xml(file_path):
    results = []
    try:
        tree = ET.parse(file_path)
        root = tree.getroot()
        testcases = root.findall(".//testcase")
        for tc in testcases:
            classname = tc.attrib.get("classname", "UnknownClass")
            name = tc.attrib.get("name", "UnknownTest")
            time = tc.attrib.get("time", "0.0")

            failure = tc.find("failure")
            error = tc.find("error")
            skipped = tc.find("skipped")

            status = "PASSED"
            message = ""
            details = ""

            if failure is not None:
                status = "FAILED"
                message = failure.attrib.get("message", failure.attrib.get("type", "Test Failed"))
                details = (failure.text or "").strip()
            elif error is not None:
                status = "ERROR"
                message = error.attrib.get("message", error.attrib.get("type", "Execution Error"))
                details = (error.text or "").strip()
            elif skipped is not None:
                status = "SKIPPED"
                message = skipped.attrib.get("message", "Skipped")

            results.append({
                "class": classname.split(".")[-1],
                "full_class": classname,
                "name": name,
                "time": time,
                "status": status,
                "message": message,
                "details": details,
            })
    except Exception as e:
        sys.stderr.write(f"Warning: Failed to parse {file_path}: {e}\n")
    return results

def main():
    xml_files = find_test_xml_files()
    if not xml_files:
        print("ℹ️ No JUnit XML test result files discovered under `app/build/`.")
        return

    all_tests = {}
    for f in xml_files:
        for item in parse_junit_xml(f):
            key = f"{item['full_class']}#{item['name']}"
            all_tests[key] = item

    if not all_tests:
        print("ℹ️ Found XML test result files but no `<testcase>` entries were recorded.")
        return

    total = len(all_tests)
    failed = [t for t in all_tests.values() if t["status"] in ("FAILED", "ERROR")]
    skipped = [t for t in all_tests.values() if t["status"] == "SKIPPED"]
    passed = [t for t in all_tests.values() if t["status"] == "PASSED"]

    print("### 📱 Instrumented AndroidTest (AVD) Execution Summary")
    print("")
    print(f"- **Total Tests Executed:** `{total}`")
    print(f"- **Passed:** `{len(passed)}` ✅")
    print(f"- **Failed:** `{len(failed)}` ❌")
    print(f"- **Skipped:** `{len(skipped)}` ⏭️")
    print("")

    if failed:
        print("#### ❌ Failed Test Cases")
        print("")
        print("| Class | Test Method | Status | Summary |")
        print("| :--- | :--- | :---: | :--- |")
        for f in failed:
            clean_msg = f['message'].replace("\n", " ").replace("|", "\\|")[:120]
            print(f"| `{f['class']}` | `{f['name']}` | **{f['status']}** | {clean_msg} |")
        print("")

        print("#### 🔍 Failure Trace Details")
        print("")
        for f in failed:
            print(f"<details>")
            print(f"<summary><b>{f['class']}.{f['name']}</b>: <i>{f['message'][:100]}</i></summary>")
            print("")
            print("```text")
            # Limit details to first 25 lines to keep summary concise
            detail_lines = f["details"].splitlines()[:25]
            print("\n".join(detail_lines) or "No stack trace recorded.")
            print("```")
            print("</details>")
            print("")
    else:
        print("🎉 **All instrumented tests passed successfully!**")
        print("")

if __name__ == "__main__":
    main()
